/**
 * Generate Dockerfile matching detected stack
 */
export function generateDockerfile(detected) {
  const port = detected.defaultPort || 3000;
  
  if (detected.type === 'node') {
    return `# Generated by runrepo (https://github.com/Terrox0/runrepo)
FROM node:${detected.runtimeVersion || '20'}-alpine
WORKDIR /app

# Install package manager if needed
${detected.packageManager === 'pnpm' ? 'RUN corepack enable && corepack prepare pnpm@latest --activate\n' : ''}\
${detected.packageManager === 'yarn' ? 'RUN corepack enable && corepack prepare yarn@stable --activate\n' : ''}\
${detected.packageManager === 'bun' ? 'RUN npm install -g bun\n' : ''}\

# Cache dependencies
COPY package*.json ${detected.packageManager === 'pnpm' ? 'pnpm-lock.yaml*' : ''} ${detected.packageManager === 'yarn' ? 'yarn.lock*' : ''} ./
RUN ${
  detected.packageManager === 'pnpm' ? 'pnpm install' :
  detected.packageManager === 'yarn' ? 'yarn install' :
  detected.packageManager === 'bun' ? 'bun install' :
  'npm install'
}

# Copy project source
COPY . .

EXPOSE ${port}
ENV PORT=${port}
ENV HOST=0.0.0.0

CMD ["sh", "-c", "${detected.runCommand}"]
`;
  }

  if (detected.type === 'python') {
    return `# Generated by runrepo (https://github.com/Terrox0/runrepo)
FROM python:${detected.runtimeVersion || '3.11'}-slim
WORKDIR /app

RUN apt-get update && apt-get install -y --no-install-recommends curl build-essential && rm -rf /var/lib/apt/lists/*

COPY requirements*.txt pyproject.toml* setup.py* ./
RUN if [ -f requirements.txt ]; then pip install --no-cache-dir -r requirements.txt; fi

COPY . .

EXPOSE ${port}
ENV PORT=${port}
ENV PYTHONUNBUFFERED=1

CMD ["sh", "-c", "${detected.runCommand}"]
`;
  }

  if (detected.type === 'go') {
    return `# Generated by runrepo (https://github.com/Terrox0/runrepo)
FROM golang:${detected.runtimeVersion || '1.22'}-alpine
WORKDIR /app

COPY go.mod go.sum* ./
RUN go mod download

COPY . .

EXPOSE ${port}
ENV PORT=${port}

CMD ["sh", "-c", "${detected.runCommand}"]
`;
  }

  if (detected.type === 'rust') {
    return `# Generated by runrepo (https://github.com/Terrox0/runrepo)
FROM rust:latest
WORKDIR /app

COPY Cargo.toml Cargo.lock* ./
RUN mkdir src && echo "fn main() {}" > src/main.rs && cargo build || true && rm -rf src

COPY . .

EXPOSE ${port}
ENV PORT=${port}

CMD ["cargo", "run"]
`;
  }

  // Fallback / Static
  return `# Generated by runrepo (https://github.com/Terrox0/runrepo)
FROM node:20-alpine
WORKDIR /app
RUN npm install -g serve
COPY . .
EXPOSE ${port}
CMD ["serve", "-s", ".", "-l", "${port}"]
`;
}

/**
 * Generate .devcontainer/devcontainer.json
 */
export function generateDevcontainer(detected) {
  const port = detected.defaultPort || 3000;
  return JSON.stringify({
    name: `runrepo (${detected.framework !== 'unknown' ? detected.framework : detected.type})`,
    build: {
      dockerfile: "../Dockerfile"
    },
    forwardPorts: [port],
    customizations: {
      vscode: {
        settings: {
          "terminal.integrated.defaultProfile.linux": "bash"
        },
        extensions: detected.type === 'node' ? [
          "dbaeumer.vscode-eslint"
        ] : detected.type === 'python' ? [
          "ms-python.python"
        ] : []
      }
    },
    postCreateCommand: detected.type === 'node' ? `${detected.packageManager} install` :
                       detected.type === 'python' ? "pip install -r requirements.txt" :
                       detected.type === 'go' ? "go mod download" : ""
  }, null, 2);
}

/**
 * Generate POSIX run.sh
 */
export function generateRunSh(detected) {
  const port = detected.defaultPort || 3000;
  return `#!/usr/bin/env bash
# ==============================================================================
# run.sh - Universal One-Command Project Runner
# Generated by runrepo (https://github.com/Terrox0/runrepo)
# ==============================================================================
set -e

DIR="$(cd "$(dirname "\${BASH_SOURCE[0]}")" >/dev/null 2>&1 && pwd)"
cd "$DIR"

# 1. Check for .env file
if [ ! -f .env ] && [ -f .env.example ]; then
  echo "[runrepo] Notice: .env not found. Initializing from .env.example..."
  cp .env.example .env
fi

# 2. Containerized run flag
if [ "$1" == "--container" ] || [ "$1" == "-c" ]; then
  echo "[runrepo] Booting in isolated Docker container (Port ${port})..."
  docker build -t runrepo-app .
  docker run -it --rm -p ${port}:${port} -v "$(pwd):/app" runrepo-app
  exit 0
fi

# 3. Native host execution fast-path
echo "[runrepo] Checking native environment for ${detected.runtime}..."
if command -v ${detected.runtime === 'node' ? detected.packageManager : detected.runtime} >/dev/null 2>&1; then
  echo "[runrepo] Launching natively: ${detected.runCommand}"
  exec ${detected.runCommand}
fi

# 4. Fallback to container if native toolchain is missing
if command -v docker >/dev/null 2>&1; then
  echo "[runrepo] Native ${detected.runtime} not found on PATH. Falling back to container..."
  docker build -t runrepo-app .
  docker run -it --rm -p ${port}:${port} -v "$(pwd):/app" runrepo-app
else
  echo "[runrepo] Error: Neither native '${detected.runtime}' nor 'docker' is installed."
  echo "[runrepo] Please install '${detected.runtime}' or Docker Desktop to run this project."
  exit 1
fi
`;
}

/**
 * Generate Windows run.bat
 */
export function generateRunBat(detected) {
  const port = detected.defaultPort || 3000;
  return `@echo off
REM ============================================================================
REM run.bat - Universal One-Command Project Runner for Windows
REM Generated by runrepo (https://github.com/Terrox0/runrepo)
REM ============================================================================

IF NOT EXIST .env (
  IF EXIST .env.example (
    echo [runrepo] Initializing .env from .env.example...
    copy .env.example .env >nul
  )
)

IF "%1"=="--container" GOTO RUN_CONTAINER
IF "%1"=="-c" GOTO RUN_CONTAINER

echo [runrepo] Launching natively: ${detected.runCommand}
${detected.runCommand}
IF %ERRORLEVEL% NEQ 0 (
  echo [runrepo] Native launch failed. Checking for Docker fallback...
  GOTO RUN_CONTAINER
)
EXIT /B 0

:RUN_CONTAINER
where docker >nul 2>&1
IF %ERRORLEVEL% EQU 0 (
  echo [runrepo] Booting in isolated Docker container (Port ${port})...
  docker build -t runrepo-app .
  docker run -it --rm -p ${port}:${port} -v "%cd%:/app" runrepo-app
) ELSE (
  echo [runrepo] Error: Native run failed and Docker was not found on PATH.
  pause
)
`;
}

/**
 * Generate .env.example if missing
 */
export function generateEnvExample(extractedVars) {
  if (!extractedVars || extractedVars.length === 0) {
    return `# Generated by runrepo
PORT=3000
NODE_ENV=development
`;
  }
  let content = '# Generated by runrepo: Detected environment variables\n';
  for (const v of extractedVars) {
    content += `${v}=your_${v.toLowerCase()}_here\n`;
  }
  return content;
}

/**
 * Generate GitHub Action: verify-reproducibility.yml
 */
export function generateWorkflow(detected) {
  return `name: Verify Reproducibility (runrepo)

on:
  push:
    branches: [ main, master ]
  pull_request:
    branches: [ main, master ]

jobs:
  verify-reproducibility:
    runs-on: ubuntu-latest
    steps:
      - name: Checkout Code
        uses: actions/checkout@v4

      - name: Verify Environment Template
        run: |
          if [ -f .env.example ]; then
            echo "✓ .env.example exists"
          else
            echo "::warning::Missing .env.example template"
          fi

      - name: Test Docker Container Build
        run: |
          if [ -f Dockerfile ]; then
            docker build -t runrepo-test .
            echo "✓ Dockerfile builds reproducibly without host dependencies"
          fi

      - name: Validate Run Script Syntax
        run: |
          if [ -f run.sh ]; then
            bash -n run.sh
            echo "✓ run.sh is valid POSIX bash"
          fi
`;
}
